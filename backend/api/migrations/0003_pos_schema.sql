-- Server-side POS data owned by the API.
--
-- The Expo app keeps its own offline SQLite database. These tables are the
-- server copy used by merchants who want a shared, multi-device ledger and by
-- the hosted checkout. Every row is scoped by business_id, so one merchant can
-- never read or write another merchant's catalogue, sales, or stock.
--
-- Conventions:
--   * Money is INTEGER ZAR cents. There are no floating point columns.
--   * Crypto amounts and rates are TEXT decimal strings, so precision survives
--     JSON and SQLite round trips unchanged.
--   * Ids are random 128-bit hex strings generated by the API, not
--     autoincrement integers, so a whole sale can be written in one batch.
--
-- D1 does not support interactive transactions over database/sql. Multi-row
-- writes therefore go through D1Database.batch(), which the platform runs as a
-- single SQL transaction. `pos_guard` is the portable equivalent of a CHECK on
-- a previous statement's row count: it stays empty on success and makes the
-- batch abort when a guarded statement changed nothing.

CREATE TABLE IF NOT EXISTS pos_businesses (
  id TEXT PRIMARY KEY,
  owner_id TEXT NOT NULL,
  name TEXT NOT NULL DEFAULT '',
  website TEXT NOT NULL DEFAULT '',
  address TEXT NOT NULL DEFAULT '',
  wallet_address TEXT NOT NULL DEFAULT '',
  logo_uri TEXT,
  created_at INTEGER NOT NULL DEFAULT 0,
  updated_at INTEGER NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_pos_businesses_owner ON pos_businesses (owner_id);

CREATE TABLE IF NOT EXISTS pos_categories (
  id TEXT PRIMARY KEY,
  business_id TEXT NOT NULL REFERENCES pos_businesses (id),
  name TEXT NOT NULL,
  created_at INTEGER NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_pos_categories_name ON pos_categories (business_id, name);

CREATE TABLE IF NOT EXISTS pos_products (
  id TEXT PRIMARY KEY,
  business_id TEXT NOT NULL REFERENCES pos_businesses (id),
  sku TEXT NOT NULL,
  name TEXT NOT NULL,
  image_uri TEXT,
  category_id TEXT REFERENCES pos_categories (id),
  price INTEGER NOT NULL DEFAULT 0 CHECK (price >= 0),
  cost_price INTEGER NOT NULL DEFAULT 0 CHECK (cost_price >= 0),
  stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
  reorder_level INTEGER NOT NULL DEFAULT 0 CHECK (reorder_level >= 0),
  active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
  created_at INTEGER NOT NULL DEFAULT 0,
  updated_at INTEGER NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_pos_products_sku ON pos_products (business_id, sku);
CREATE INDEX IF NOT EXISTS idx_pos_products_category ON pos_products (business_id, category_id);

CREATE TABLE IF NOT EXISTS pos_customers (
  id TEXT PRIMARY KEY,
  business_id TEXT NOT NULL REFERENCES pos_businesses (id),
  name TEXT NOT NULL,
  phone TEXT,
  loyalty_points INTEGER NOT NULL DEFAULT 0 CHECK (loyalty_points >= 0),
  created_at INTEGER NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_pos_customers_phone ON pos_customers (business_id, phone);

CREATE TABLE IF NOT EXISTS pos_sales (
  id TEXT PRIMARY KEY,
  business_id TEXT NOT NULL REFERENCES pos_businesses (id),
  receipt_no TEXT NOT NULL,
  created_at INTEGER NOT NULL DEFAULT 0,
  updated_at INTEGER NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'completed', 'failed', 'voided', 'refunded', 'partially_refunded')),
  customer_id TEXT REFERENCES pos_customers (id),
  subtotal INTEGER NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
  discount_type TEXT NOT NULL DEFAULT 'none'
    CHECK (discount_type IN ('none', 'percent', 'fixed')),
  discount_value INTEGER NOT NULL DEFAULT 0 CHECK (discount_value >= 0),
  discount_amount INTEGER NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
  points_redeemed INTEGER NOT NULL DEFAULT 0 CHECK (points_redeemed >= 0),
  points_discount INTEGER NOT NULL DEFAULT 0 CHECK (points_discount >= 0),
  total INTEGER NOT NULL DEFAULT 0 CHECK (total >= 0),
  cost_total INTEGER NOT NULL DEFAULT 0 CHECK (cost_total >= 0),
  payment_method TEXT NOT NULL DEFAULT '',
  payment_status TEXT NOT NULL DEFAULT 'pending'
    CHECK (payment_status IN ('pending', 'success', 'failed')),
  crypto_amount TEXT NOT NULL DEFAULT '0',
  crypto_rate TEXT NOT NULL DEFAULT '0',
  tx_hash TEXT,
  failure_reason TEXT,
  points_earned INTEGER NOT NULL DEFAULT 0 CHECK (points_earned >= 0),
  refunded_total INTEGER NOT NULL DEFAULT 0 CHECK (refunded_total >= 0),
  voided_at INTEGER,
  void_reason TEXT,
  CHECK (refunded_total <= total)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_pos_sales_receipt ON pos_sales (business_id, receipt_no);
CREATE INDEX IF NOT EXISTS idx_pos_sales_created ON pos_sales (business_id, created_at);
CREATE INDEX IF NOT EXISTS idx_pos_sales_status ON pos_sales (business_id, status);

CREATE TABLE IF NOT EXISTS pos_sale_items (
  id TEXT PRIMARY KEY,
  sale_id TEXT NOT NULL REFERENCES pos_sales (id),
  product_id TEXT NOT NULL REFERENCES pos_products (id),
  sku TEXT NOT NULL,
  name TEXT NOT NULL,
  qty INTEGER NOT NULL CHECK (qty > 0),
  unit_price INTEGER NOT NULL CHECK (unit_price >= 0),
  unit_cost INTEGER NOT NULL DEFAULT 0 CHECK (unit_cost >= 0),
  line_discount INTEGER NOT NULL DEFAULT 0 CHECK (line_discount >= 0),
  refunded_qty INTEGER NOT NULL DEFAULT 0 CHECK (refunded_qty >= 0),
  refunded_amount INTEGER NOT NULL DEFAULT 0 CHECK (refunded_amount >= 0),
  CHECK (refunded_qty <= qty)
);

CREATE INDEX IF NOT EXISTS idx_pos_sale_items_sale ON pos_sale_items (sale_id);

CREATE TABLE IF NOT EXISTS pos_refunds (
  id TEXT PRIMARY KEY,
  business_id TEXT NOT NULL REFERENCES pos_businesses (id),
  sale_id TEXT NOT NULL REFERENCES pos_sales (id),
  created_at INTEGER NOT NULL DEFAULT 0,
  amount INTEGER NOT NULL DEFAULT 0 CHECK (amount >= 0),
  reason TEXT,
  restocked INTEGER NOT NULL DEFAULT 1 CHECK (restocked IN (0, 1)),
  points_reversed INTEGER NOT NULL DEFAULT 0 CHECK (points_reversed >= 0)
);

CREATE INDEX IF NOT EXISTS idx_pos_refunds_sale ON pos_refunds (sale_id);

CREATE TABLE IF NOT EXISTS pos_refund_items (
  id TEXT PRIMARY KEY,
  refund_id TEXT NOT NULL REFERENCES pos_refunds (id),
  sale_item_id TEXT NOT NULL REFERENCES pos_sale_items (id),
  qty INTEGER NOT NULL CHECK (qty > 0),
  amount INTEGER NOT NULL DEFAULT 0 CHECK (amount >= 0),
  cost_recovered INTEGER NOT NULL DEFAULT 0 CHECK (cost_recovered >= 0),
  UNIQUE (refund_id, sale_item_id)
);

CREATE INDEX IF NOT EXISTS idx_pos_refund_items_refund ON pos_refund_items (refund_id);

CREATE TABLE IF NOT EXISTS pos_stock_movements (
  id TEXT PRIMARY KEY,
  business_id TEXT NOT NULL REFERENCES pos_businesses (id),
  product_id TEXT NOT NULL REFERENCES pos_products (id),
  type TEXT NOT NULL
    CHECK (type IN ('initial', 'sale', 'refund', 'void', 'restock', 'adjustment')),
  quantity INTEGER NOT NULL,
  balance_after INTEGER NOT NULL CHECK (balance_after >= 0),
  unit_cost INTEGER CHECK (unit_cost IS NULL OR unit_cost >= 0),
  reference TEXT,
  note TEXT,
  created_at INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_pos_stock_movements_product
  ON pos_stock_movements (business_id, product_id, created_at);
CREATE INDEX IF NOT EXISTS idx_pos_stock_movements_created
  ON pos_stock_movements (business_id, created_at);

CREATE TABLE IF NOT EXISTS pos_receipt_counters (
  business_id TEXT PRIMARY KEY REFERENCES pos_businesses (id),
  next_no INTEGER NOT NULL DEFAULT 1 CHECK (next_no > 0)
);

CREATE TABLE IF NOT EXISTS pos_idempotency (
  business_id TEXT NOT NULL,
  idem_key TEXT NOT NULL,
  scope TEXT NOT NULL DEFAULT '',
  request_hash TEXT NOT NULL DEFAULT '',
  response_json TEXT NOT NULL DEFAULT '',
  created_at INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (business_id, idem_key)
);

CREATE TABLE IF NOT EXISTS pos_guard (
  ok INTEGER NOT NULL CHECK (ok = 1)
);
